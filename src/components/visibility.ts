import type { Owner } from '../engine/types';
import type { GameMode } from '../store/gameStore';

/**
 * **상대의 미공개 정보를 감출 것인가.**
 *
 * 이 게임은 원래 한 화면에서 양쪽을 다 조종하는 디버그 모드로 만들어졌다 — 편성도 배치도 매 턴
 * 계획도 전부 한 판에 띄우는 것이 전제였고, 서로 다른 화면을 보는 대전이 없었으니 감출 이유도
 * 없었다. 온라인이 생기면서 그 전제가 깨졌다. 상대 계획이 보이면 "동시에 내고 한꺼번에 공개한다"는
 * 규칙이 껍데기만 남고, 실제로는 **늦게 정하는 쪽이 언제나 이기는 게임**이 된다.
 *
 * 감추는 것과 감추지 않는 것의 경계는 **아직 공개되지 않았는가**다.
 * - 감춘다: 상대 편성(드래프트 중) · 상대 배치(배치 화면) · 상대의 이번 턴 계획(이동 미리보기).
 * - 감추지 않는다: 해결이 끝난 판 위 위치 · 체력 · 쿨타임 · 로그. 이건 양쪽이 함께 본 결과라
 *   한쪽만 아는 정보가 아니고, 감추면 다음 수를 세울 근거 자체가 사라진다.
 *
 * **한계(솔직히):** 가리는 곳은 화면뿐이다. 온라인은 호스트 권위 구조라 호스트 브라우저의
 * 스토어에는 게스트의 계획이 그대로 들어 있고(게스트가 조작을 보내면 호스트가 실행한다),
 * 게스트에게도 전체 스냅샷이 그대로 간다. 개발자 도구를 열면 볼 수 있다. 진짜로 막으려면
 * 계획을 해시로 먼저 보내고 나중에 원본을 까는 커밋-공개 방식이 필요한데, 그건 네트워크
 * 계층을 다시 짜는 일이라 여기서는 하지 않았다.
 */
export function hidesOpponentInfo(mode: GameMode): boolean {
  return mode === 'online';
}

/**
 * `owner`의 미공개 정보를 `localOwner`가 볼 수 있는가.
 * 로컬 대전은 한 사람이 양쪽을 조종하므로 감출 상대가 없고, AI 대전은 AI가 사람 화면을 보고
 * 두는 것이 아니라 정보 우위가 생기지 않는다 — 오히려 AI 계획이 보이는 편이 배우기에 좋다.
 */
export function canSeeHiddenInfo(mode: GameMode, localOwner: Owner, owner: Owner): boolean {
  return !hidesOpponentInfo(mode) || owner === localOwner;
}
